def create_comprehensive_csv():
    """
    전체 데이터를 통합하여 RAG용 CSV 생성
    """
    # 데이터 수집
    insurance_companies = extract_insurance_companies_data()
    guidelines = extract_guidelines_data()
    
    # 통합 데이터프레임 생성 (RAG 최적화)
    all_data = []
    
    # 보험회사 데이터 변환
    for company in insurance_companies:
        all_data.append({
            'id': f"company_{len(all_data)+1}",
            'type': '보험회사정보',
            'category': company['카테고리'],
            'title': company['회사명'],
            'content': f"{company['회사명']} - 주소: {company['주소']}, 전화: {company['전화번호']}, 웹사이트: {company['웹사이트']}",
            'keywords': f"보험회사,{company['회사명']},{company['전화번호']}",
            'metadata': f"주소:{company['주소']}|전화:{company['전화번호']}|웹:{company['웹사이트']}"
        })
    
    # 안내사항 데이터 변환  
    for guide in guidelines:
        all_data.append({
            'id': f"guide_{len(all_data)+1}",
            'type': guide['섹션'],
            'category': guide['카테고리'], 
            'title': guide['제목'],
            'content': guide['내용'],
            'keywords': guide['키워드'],
            'metadata': f"항목번호:{guide['항목번호']}|섹션:{guide['섹션']}"
        })
    
    # 데이터프레임 생성
    df = pd.DataFrame(all_data)
    
    # CSV 파일 저장
    csv_filename = '교통사고_협의서_RAG_데이터.csv'
    df.to_csv(csv_filename, index=False, encoding='utf-8-sig')
    
    print(f"✅ CSV 파일이 생성되었습니다: {csv_filename}")
    print(f"📊 총 {len(df)} 개의 레코드가 저장되었습니다.")
    print("\n📋 데이터 구조:")
    print(df.info())
    print("\n🔍 첫 5개 레코드 미리보기:")
    print(df.head())
    
    return df, csv_filename

